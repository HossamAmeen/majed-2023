from collections.abc import Sequence
from typing import Any

from django.http import HttpResponse
from django.utils import timezone
from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import OpenApiParameter, OpenApiResponse, extend_schema, extend_schema_view
from rest_framework import status, viewsets
from rest_framework.decorators import action
from rest_framework.exceptions import NotFound
from rest_framework.permissions import IsAuthenticated
from rest_framework.request import Request
from rest_framework.response import Response
from rest_framework.serializers import BaseSerializer

from apps.common.permissions import IsMaster
from apps.products.exports import ProductExcelExporter, ProductPdfExporter
from apps.products.filters import ProductFilter
from apps.products.models import Product
from apps.products.selectors import ProductSelector
from apps.products.serializers import (
    ProductLookupSerializer,
    ProductSerializer,
    ProductSummarySerializer,
    ProductWriteSerializer,
)
from apps.products.services import ProductService

XLSX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"


@extend_schema_view(
    list=extend_schema(tags=["products"]),
    retrieve=extend_schema(tags=["products"]),
    create=extend_schema(
        tags=["products"], request=ProductWriteSerializer, responses={201: ProductSerializer}
    ),
    update=extend_schema(tags=["products"], request=ProductWriteSerializer, responses=ProductSerializer),
    partial_update=extend_schema(
        tags=["products"], request=ProductWriteSerializer, responses=ProductSerializer
    ),
    destroy=extend_schema(tags=["products"]),
)
class ProductViewSet(viewsets.ModelViewSet):  # type: ignore[type-arg]
    """
    Stock management (master only). The product code is generated by the server.

    `by-code` is open to every signed-in user because the bill screen uses it.
    """

    permission_classes = [IsMaster]
    filterset_class = ProductFilter
    search_fields = ["name", "=code"]
    ordering_fields = ["id", "name", "quantity", "selling_price", "purchasing_price", "updated_at"]

    def get_queryset(self):  # type: ignore[no-untyped-def]
        return ProductSelector.list()

    def get_permissions(self) -> Sequence[Any]:
        if self.action == "by_code":
            return [IsAuthenticated()]
        return super().get_permissions()

    def get_serializer_class(self) -> type[BaseSerializer]:  # type: ignore[type-arg]
        if self.action in {"create", "update", "partial_update"}:
            return ProductWriteSerializer
        return ProductSerializer

    def create(self, request: Request, *args: Any, **kwargs: Any) -> Response:
        serializer = self.get_serializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        product = ProductService.create_product(actor=request.user, data=serializer.validated_data)  # type: ignore[arg-type]
        return Response(ProductSerializer(product).data, status=status.HTTP_201_CREATED)

    def update(self, request: Request, *args: Any, **kwargs: Any) -> Response:
        instance = self.get_object()
        serializer = self.get_serializer(instance, data=request.data, partial=kwargs.pop("partial", False))
        serializer.is_valid(raise_exception=True)
        product = ProductService.update_product(
            actor=request.user, product=instance, data=serializer.validated_data  # type: ignore[arg-type]
        )
        return Response(ProductSerializer(product).data)

    def perform_destroy(self, instance: Product) -> None:
        ProductService.delete_product(actor=self.request.user, product=instance)  # type: ignore[arg-type]

    @extend_schema(tags=["products"], responses=ProductSummarySerializer)
    @action(detail=False, methods=["get"])
    def summary(self, request: Request) -> Response:
        """Totals for the products matching the same filters as the list."""
        totals = ProductSelector.summary(self.filter_queryset(self.get_queryset()))
        data = {
            **totals,
            "expected_profit": totals["total_selling_price"] - totals["total_purchasing_price"],  # type: ignore[operator]
        }
        return Response(ProductSummarySerializer(data).data)

    @extend_schema(
        tags=["products"],
        responses={200: ProductLookupSerializer, 404: OpenApiResponse(description="لا يوجد")},
    )
    @action(detail=False, methods=["get"], url_path=r"by-code/(?P<code>\d+)")
    def by_code(self, request: Request, code: str) -> Response:
        """Look a product up by its barcode number."""
        product = ProductSelector.by_code(int(code))
        if product is None:
            raise NotFound("لا يوجد منتج بهذا الكود")
        return Response(ProductLookupSerializer(product).data)

    @extend_schema(
        tags=["products"],
        parameters=[OpenApiParameter("year", OpenApiTypes.INT, description="Defaults to this year")],
        responses={(200, XLSX_CONTENT_TYPE): OpenApiTypes.BINARY},
    )
    @action(detail=False, methods=["get"], url_path="export/excel")
    def export_excel(self, request: Request) -> HttpResponse:
        """Products created in the given year, as an .xlsx sheet."""
        year = self._export_year(request)
        content = ProductExcelExporter.build(ProductSelector.created_in_year(year))
        return self._file_response(content, XLSX_CONTENT_TYPE, f"products-{year}.xlsx")

    @extend_schema(
        tags=["products"],
        parameters=[OpenApiParameter("year", OpenApiTypes.INT, description="Defaults to this year")],
        responses={(200, "application/pdf"): OpenApiTypes.BINARY},
    )
    @action(detail=False, methods=["get"], url_path="export/pdf")
    def export_pdf(self, request: Request) -> HttpResponse:
        """Products created in the given year, as a PDF table."""
        year = self._export_year(request)
        content = ProductPdfExporter.build(ProductSelector.created_in_year(year), title=f"منتجات سنة {year}")
        return self._file_response(content, "application/pdf", f"products-{year}.pdf")

    @staticmethod
    def _export_year(request: Request) -> int:
        raw = request.query_params.get("year", "")
        return int(raw) if raw.isdigit() else timezone.localdate().year

    @staticmethod
    def _file_response(content: bytes, content_type: str, filename: str) -> HttpResponse:
        response = HttpResponse(content, content_type=content_type)
        response["Content-Disposition"] = f'attachment; filename="{filename}"'
        return response
